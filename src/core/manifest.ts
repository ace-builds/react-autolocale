import fs from "node:fs";
import path from "node:path";
import { readJson, writeJson, writeFileAtomic } from "./files.js";
import { headStrings } from "./head.js";
import { findCollisions, messageId } from "./ids.js";
import type { Project } from "./project.js";
import { scanProjectDetailed } from "./scan.js";

export const MANIFEST_VERSION = 1;

export interface ManifestMessage {
  /** Source text, exactly as extracted (also what the runtime shows when a translation is missing). */
  text: string;
  /** Element or attribute it first appears in ("button", "placeholder", "head", ...). */
  context: string;
  /** Project-relative files that contain it. */
  files: string[];
  /** "unused": no longer in the source. Its translations are kept until `clean` removes them. */
  status: "active" | "unused";
}

export interface Manifest {
  version: number;
  sourceLocale: string;
  /** Catalog directory this manifest was last written for, relative to the project root. */
  output: string;
  messages: Record<string, ManifestMessage>;
}

export function manifestFile(project: Project): string {
  return path.join(project.meta, "manifest.json");
}

export function readManifest(project: Project): Manifest | null {
  const m = readJson<Manifest | null>(manifestFile(project), null);
  if (m && m.version !== MANIFEST_VERSION) {
    throw new Error(`${manifestFile(project)} has version ${m.version}; this react-autolocale understands version ${MANIFEST_VERSION}. Update the package.`);
  }
  return m;
}

export interface ScanReport {
  manifest: Manifest;
  fileCount: number;
  /** Ids of active messages. */
  active: string[];
  /** Ids seen for the first time. */
  added: string[];
  /** Ids that disappeared from the source in this scan. */
  removed: string[];
  /** Set when the previous manifest was written for a different catalog directory. */
  previousOutput?: string;
  /** Set when the source language changed since the last scan. */
  previousSource?: string;
}

/** Scans the source, updates .auto-locale/manifest.json and the source-language catalog. Never translates. */
export function scanProject(project: Project): ScanReport {
  const { root, site } = project;
  const scan = scanProjectDetailed(root, project.include, { skip: [project.output, project.meta] });
  if (site.seo) {
    const html = path.join(root, "index.html");
    if (fs.existsSync(html)) {
      for (const s of headStrings(fs.readFileSync(html, "utf8"))) {
        if (!scan.files[s]) scan.strings.push(s);
        scan.contexts[s] ??= "head";
        (scan.files[s] ??= []).push("index.html");
      }
    }
  }
  const collisions = findCollisions(scan.strings);
  if (collisions.length) {
    throw new Error(
      "Two different strings got the same message id (extremely rare). Reword one of them slightly:\n" +
        collisions.map(([a, b]) => `  "${a}"  vs  "${b}"`).join("\n"),
    );
  }

  const prev = readManifest(project);
  const messages: Record<string, ManifestMessage> = {};
  for (const [id, m] of Object.entries(prev?.messages ?? {})) messages[id] = { ...m, status: "unused" };
  const active: string[] = [];
  const added: string[] = [];
  for (const text of scan.strings) {
    const id = messageId(text);
    if (!prev?.messages[id]) added.push(id);
    active.push(id);
    messages[id] = { text, context: scan.contexts[text] ?? "", files: [...new Set(scan.files[text] ?? [])].sort(), status: "active" };
  }
  const removed = Object.keys(messages).filter((id) => messages[id]!.status === "unused" && prev?.messages[id]?.status === "active");

  const manifest: Manifest = { version: MANIFEST_VERSION, sourceLocale: site.original, output: project.outputRel, messages };
  writeJson(manifestFile(project), manifest);
  writeJson(path.join(project.output, `${site.original}.json`), Object.fromEntries(Object.entries(messages).map(([id, m]) => [id, m.text])));
  writeIndex(project);

  return {
    manifest,
    fileCount: scan.fileCount,
    active,
    added,
    removed,
    previousOutput: prev && prev.output !== project.outputRel ? prev.output : undefined,
    previousSource: prev && prev.sourceLocale !== site.original ? prev.sourceLocale : undefined,
  };
}

/** A small, stable module describing the catalogs, for code that wants to read them directly. */
function writeIndex(project: Project): void {
  const ts = fs.existsSync(path.join(project.root, "tsconfig.json"));
  const file = path.join(project.output, ts ? "index.ts" : "index.js");
  const locales = [project.site.original, ...project.site.languages];
  const content =
    `// Generated by react-autolocale. Do not edit: run \`npx react-autolocale generate\` to update.\n` +
    `export const sourceLocale = ${JSON.stringify(project.site.original)};\n` +
    `export const locales = ${JSON.stringify(locales)}${ts ? " as const" : ""};\n` +
    `/** Catalog files in this folder: message id -> text. */\n` +
    `export const catalogFiles = {${locales.map((l) => ` ${JSON.stringify(l)}: "./${l}.json"`).join(",")} };\n`;
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) writeFileAtomic(file, content);
}
